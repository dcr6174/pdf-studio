import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {build} from 'vite';
import {renderToStaticMarkup} from 'react-dom/server';
import {createElement} from 'react';
await build({configFile:false,logLevel:'error',resolve:{alias:{'@':resolve('.')}},build:{ssr:'app/page.tsx',outDir:'.home-check',emptyOutDir:true,rollupOptions:{output:{entryFileNames:'page.mjs'}}}});
const {default:Home}=await import('../.home-check/page.mjs');
const html=renderToStaticMarkup(createElement(Home));
assert.equal((html.match(/<h1>/g)||[]).length,1,'exactly one H1');
assert.ok(html.includes('Everything you need to work with PDFs.'),'hero headline is server-rendered');
assert.ok(!html.includes('Drop your PDF here'),'home has no upload invitation');
assert.ok(!/buddy/i.test(html),'no buddy mascot on the homepage');
assert.ok(!/arcade/i.test(html),'no games on the homepage');
assert.ok(new Set([...html.matchAll(/href="(\/tools\/[^"]+)"/g)].map(m=>m[1])).size>=6,'popular tool routes are crawlable before hydration');
assert.ok(html.includes('href="/tools"'),'full directory is linked');
assert.ok(html.includes('href="/guides"'),'guide hub remains linked');
assert.ok(html.includes('href="/privacy"')&&html.includes('href="/about"'));
assert.ok(!html.includes('app-sidebar'));
assert.ok(html.includes('Can I edit existing PDF text?'),'FAQ is server-rendered');
assert.ok(!/Actual processing limits|161\.3 MB|50 MB|400 pages|22 megapixels|20 files/.test(html),'no upfront limit table or numbers');
assert.ok(!html.includes('60+ free tools')&&!html.includes('Search 60+ PDF tools'),'no hardcoded tool counts');
const tools=await readFile('lib/tools.ts','utf8'),readme=await readFile('README.md','utf8');
const names=[...tools.matchAll(/^\['[^']+','([^']+)'/gm)].map(m=>m[1]);
assert.ok(names.length>=60,'catalogue intact');
assert.ok(!/arcade|game/i.test(readme),'README carries no games');
assert.ok(readme.includes('PDF_TOOL_COUNT'),'README explains the live catalogue count');
console.log(`PASS: homepage SSR (one H1, hero, crawlable routes, FAQ, no buddy/games, no hardcoded counts) and README consistency for ${names.length} tools.`);

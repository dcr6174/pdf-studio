import assert from 'node:assert/strict';
import {parsePreferences,recentSlugs,rememberGame,validSelect} from '../lib/arcade-preferences.ts';
const values=new Map();const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
assert.deepEqual(parsePreferences('{bad'),{});
assert.deepEqual(parsePreferences('{"overs":"5","sound":true,"evil":{}}'),{overs:'5',sound:true});
assert.equal(validSelect('5',['2','5','10']),true);
assert.equal(validSelect('99',['2','5','10']),false);
assert.deepEqual(recentSlugs('{bad'),[]);
assert.deepEqual(recentSlugs('["boundary-cricket","boundary-cricket",7,"../bad"]'),['boundary-cricket']);
rememberGame(storage,'memory-match');rememberGame(storage,'boundary-cricket');rememberGame(storage,'memory-match');
assert.deepEqual(recentSlugs(storage.getItem('studio-arcade:recent')),['memory-match','boundary-cricket']);
for(let i=0;i<9;i++)rememberGame(storage,'game-'+i);
assert.equal(recentSlugs(storage.getItem('studio-arcade:recent')).length,5);
const blocked={getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}};
assert.doesNotThrow(()=>rememberGame(blocked,'memory-match'));
console.log('PASS: remembered settings, validation, recent order, limits and blocked storage');

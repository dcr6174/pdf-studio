import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile('lib/signing-page-placement.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {resolveSigningPages,copySigningMark}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const pages=[{id:'p1'},{id:'p2'},{id:'p3'},{id:'p4'}];
assert.deepEqual(resolveSigningPages(pages,'p2','current','').map(p=>p.id),['p2']);
assert.deepEqual(resolveSigningPages(pages,'p2','all','').map(p=>p.id),['p1','p2','p3','p4']);
assert.deepEqual(resolveSigningPages(pages,'p2','all-except-last','').map(p=>p.id),['p1','p2','p3']);
assert.deepEqual(resolveSigningPages(pages,'p2','last','').map(p=>p.id),['p4']);
assert.deepEqual(resolveSigningPages(pages,'p2','custom','1, 3-4').map(p=>p.id),['p1','p3','p4']);
assert.throws(()=>resolveSigningPages(pages,'p2','custom',''),/Enter page numbers/);
assert.throws(()=>resolveSigningPages(pages,'p2','custom','2-8'),/Choose pages between/);
assert.throws(()=>resolveSigningPages(pages,'unknown','current',''),/at least one page/);
const mark={id:'sig1',pageId:'p2',kind:'image',image:'data:image/png;base64,abc',x:.2,y:.4,w:.3,h:.12};
const unrelated={id:'text1',pageId:'p1',kind:'text',text:'Other field'};
const first=copySigningMark([mark,unrelated],mark,pages,'all','',()=> 'copy');
assert.equal(first.pageCount,4);
assert.deepEqual(first.marks.map(m=>m.pageId),['p1','p2','p1','p3','p4']);
assert.equal(first.marks[0].id,'text1');
assert.ok(first.marks.slice(1).every(m=>m.signatureGroup==='sig1'));
const repeated=copySigningMark(first.marks,first.marks.find(m=>m.id==='sig1'),pages,'custom','3-4',()=> 'next');
assert.deepEqual(repeated.marks.filter(m=>m.signatureGroup==='sig1').map(m=>m.pageId),['p2','p3','p4']);
console.log('PASS: signing page scope selection, range validation, source retention, repeated application and unrelated marks.');

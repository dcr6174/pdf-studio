import assert from 'node:assert/strict';
import {build} from 'vite';
await build({configFile:false,logLevel:'error',build:{ssr:true,outDir:'.audit-list-one-check',emptyOutDir:true,rollupOptions:{input:{'task-readiness':'lib/task-readiness.ts','sensitive-text':'lib/sensitive-text.ts','task-action-label':'lib/task-action-label.ts','extra-pdf':'lib/extra-pdf.ts'},output:{entryFileNames:'[name].mjs'}}}});
const {taskInputIssue}=await import('../.audit-list-one-check/task-readiness.mjs');
const {sensitiveTextCandidates}=await import('../.audit-list-one-check/sensitive-text.mjs');
const {taskActionLabel}=await import('../.audit-list-one-check/task-action-label.mjs');
const options={text:'',recipe:undefined,workflowSteps:undefined,workflowDisabled:undefined};
assert.match(taskInputIssue('create',0,options),/Type/);
assert.match(taskInputIssue('markdown',0,{...options,text:'  '}),/Type/);
assert.match(taskInputIssue('create-form',0,options),/field label/);
assert.match(taskInputIssue('bookmarks',1,options),/bookmark/);
assert.match(taskInputIssue('merge',1,options),/one more/);
assert.equal(taskInputIssue('merge',2,options),'');
assert.match(taskInputIssue('workflow',1,options),/two PDFs/);
assert.match(taskInputIssue('workflow',2,options,true),/One document/);
assert.equal(taskInputIssue('workflow',1,{...options,recipe:'email-ready'}),'');
assert.match(taskInputIssue('workflow',2,{...options,recipe:'custom',workflowSteps:['compress','merge']}),/first step/);
assert.match(taskInputIssue('workflow',2,{...options,recipe:'custom',workflowSteps:['merge'],workflowDisabled:[0]}),/enabled/);
assert.equal(taskInputIssue('create',0,{...options,text:'Hello'}),'');
for(const phone of ['+44 20 7946 0958','+1 (415) 555-2671','(212) 555-0100','212-555-0100','+91 98765 43210'])assert.ok(sensitiveTextCandidates('Contact: '+phone).includes(phone),phone);
assert.equal(sensitiveTextCandidates('Date: 2026-10-06, reference 1234').length,0);
assert.equal(taskActionLabel('merge',1),'Add one more PDF');
assert.equal(taskActionLabel('merge',2),'Merge 2 files');
assert.equal(taskActionLabel('numbers',1),'Add page numbers');
assert.equal(taskActionLabel('edit',1),'Download edited PDF');
console.log('PASS: empty inputs, workflow validity, action labels and international phone candidates.');

const {PDFDocument,PDFTextField,PDFCheckBox}=await import('pdf-lib');
const {createForm}=await import('../.audit-list-one-check/extra-pdf.mjs');
const formDoc=await createForm('Full name\n[checkbox] I agree');
const reopened=await PDFDocument.load(await formDoc.save());
const createdFields=reopened.getForm().getFields();
assert.equal(createdFields.length,2);
assert.ok(createdFields[0] instanceof PDFTextField);
assert.ok(createdFields[1] instanceof PDFCheckBox);
createdFields[0].setText('Sample Person');createdFields[1].check();
const filled=await PDFDocument.load(await reopened.save());
assert.equal(filled.getForm().getTextField(createdFields[0].getName()).getText(),'Sample Person');
assert.equal(filled.getForm().getCheckBox(createdFields[1].getName()).isChecked(),true);
console.log('PASS: fillable text field and checkbox survive saving and reopening.');
